# Import pandas for handling the dataset
import pandas as pd

# Import matplotlib for creating graphs
import matplotlib.pyplot as plt

# Import seaborn for data visualization
import seaborn as sns

# Import machine learning functions
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LogisticRegression

# Import evaluation metrics
from sklearn.metrics import accuracy_score, confusion_matrix, classification_report

print("Libraries imported successfully!")

# Load the Titanic dataset from the uploaded CSV file
df = pd.read_csv("Titanic-Dataset.csv")

# Display the first 5 rows
df.head()

# Display the number of rows and columns
print("Dataset Shape:", df.shape)

# Display the column names
print("\nColumn Names:")
print(df.columns.tolist())

# Display information about the dataset
print("\nDataset Information:")
df.info()

# Check how many values are missing in each column
print("Missing Values:")
print(df.isnull().sum())

# Create a graph showing how many passengers survived
sns.countplot(data=df, x="Survived")

# Add a title
plt.title("Titanic Survival Distribution")

# Label the axes
plt.xlabel("Survived (0 = No, 1 = Yes)")
plt.ylabel("Number of Passengers")

# Show the graph
plt.show()

# Compare survival between male and female passengers
sns.countplot(data=df, x="Sex", hue="Survived")

# Add a title
plt.title("Survival by Gender")

# Label the axes
plt.xlabel("Gender")
plt.ylabel("Number of Passengers")

# Show the graph
plt.show()

# Make a copy of the original dataset
data = df.copy()

# Fill missing Age values with the median age
data["Age"] = data["Age"].fillna(data["Age"].median())

# Fill missing Embarked values with the most common value
data["Embarked"] = data["Embarked"].fillna(data["Embarked"].mode()[0])

# Fill missing Fare values with the median fare
data["Fare"] = data["Fare"].fillna(data["Fare"].median())

# We don't use Cabin because it contains many missing values

print("Data cleaning completed!")

# Select the features we want to use for prediction
X = data[[
    "Pclass",
    "Sex",
    "Age",
    "SibSp",
    "Parch",
    "Fare",
    "Embarked"
]]

# Select the target variable
# 0 = Did not survive
# 1 = Survived
y = data["Survived"]

# Convert text columns into numerical columns
X = pd.get_dummies(
    X,
    columns=["Sex", "Embarked"],
    drop_first=True
)

# Display the prepared data
X.head()

# Split the dataset into training and testing data
# 80% is used for training
# 20% is used for testing

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42
)

# Create the Logistic Regression model
model = LogisticRegression(max_iter=1000)

# Train the model
model.fit(X_train, y_train)

print("Model trained successfully!")

# Use the trained model to make predictions
y_pred = model.predict(X_test)

# Calculate the accuracy
accuracy = accuracy_score(y_test, y_pred)

# Display the accuracy
print("Model Accuracy:", round(accuracy * 100, 2), "%")

# Display the classification report
print("Classification Report:")
print(classification_report(y_test, y_pred))

# Calculate the confusion matrix
cm = confusion_matrix(y_test, y_pred)

# Display the confusion matrix as a heatmap
sns.heatmap(
    cm,
    annot=True,
    fmt="d",
    xticklabels=["Did Not Survive", "Survived"],
    yticklabels=["Did Not Survive", "Survived"]
)

# Add title and labels
plt.title("Confusion Matrix")
plt.xlabel("Predicted")
plt.ylabel("Actual")

# Display the graph
plt.show()

# Create information for one example passenger
sample = pd.DataFrame({
    "Pclass": [3],
    "Age": [25],
    "SibSp": [0],
    "Parch": [0],
    "Fare": [10],
    "Sex_male": [1],
    "Embarked_Q": [0],
    "Embarked_S": [1]
})

# Make sure the sample has the same columns as the training data
sample = sample.reindex(columns=X.columns, fill_value=0)

# Predict whether the passenger survived
prediction = model.predict(sample)

# Display the prediction
if prediction[0] == 1:
    print("Prediction: Passenger is likely to SURVIVE.")
else:
    print("Prediction: Passenger is likely to NOT SURVIVE.")
