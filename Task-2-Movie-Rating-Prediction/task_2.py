# Import pandas for working with the dataset
import pandas as pd

# Import numpy for numerical calculations
import numpy as np

# Import matplotlib for creating graphs
import matplotlib.pyplot as plt

# Import seaborn for data visualization
import seaborn as sns

# Import train_test_split to divide data into training and testing sets
from sklearn.model_selection import train_test_split

# Import Linear Regression for predicting movie ratings
from sklearn.linear_model import LinearRegression

# Import evaluation metrics
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

print("Libraries imported successfully!")

# Load the IMDb Movies India dataset
df = pd.read_csv("IMDb Movies India.csv", encoding="latin1")

# Display the first 5 rows of the dataset
df.head()

# Display the number of rows and columns
print("Dataset Shape:", df.shape)

# Display all column names
print("\nColumn Names:")
print(df.columns.tolist())

# Display information about the dataset
print("\nDataset Information:")
df.info()

# Check the number of missing values in each column
missing_values = df.isnull().sum()

# Display missing values
print("Missing Values in Each Column:")
print(missing_values)

# Display basic statistics of the Rating column
print(df["Rating"].describe())

# Create a histogram showing the distribution of movie ratings
sns.histplot(data=df, x="Rating", bins=20, kde=True)

# Add title and labels
plt.title("Distribution of Movie Ratings")
plt.xlabel("Movie Rating")
plt.ylabel("Number of Movies")

# Display the graph
plt.show()

# Remove rows where Genre is missing
genre_data = df.dropna(subset=["Genre"])

# Display the 10 most common genres
top_genres = genre_data["Genre"].value_counts().head(10)

print("Top 10 Genres:")
print(top_genres)

# Create a bar graph
top_genres.plot(kind="bar", figsize=(10, 5))

# Add title and labels
plt.title("Top 10 Movie Genres")
plt.xlabel("Genre")
plt.ylabel("Number of Movies")

# Rotate genre names for better visibility
plt.xticks(rotation=45)

# Display the graph
plt.show()

# Create a copy of the dataset
data = df.copy()

# Convert Year into a numerical value
# Example: "(2019)" becomes 2019
data["Year"] = data["Year"].str.extract(r"(\d{4})").astype(float)

# Convert Duration into numerical minutes
# Example: "120 min" becomes 120
data["Duration"] = data["Duration"].str.extract(r"(\d+)").astype(float)

# Convert Votes into numerical values
data["Votes"] = pd.to_numeric(
    data["Votes"].astype(str).str.replace(",", "", regex=False),
    errors="coerce"
)

# Convert Rating into numerical format
data["Rating"] = pd.to_numeric(data["Rating"], errors="coerce")

# Select the features used for prediction
features = ["Year", "Duration", "Votes"]

# Remove rows where any required value is missing
data = data.dropna(subset=features + ["Rating"])

# Display the cleaned data
data[features + ["Rating"]].head()

# Select input features
X = data[["Year", "Duration", "Votes"]]

# Select the target variable
# Rating is the value we want to predict
y = data["Rating"]

# Split the data into training and testing sets
# 80% is used for training
# 20% is used for testing
X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42
)

# Create the Linear Regression model
model = LinearRegression()

# Train the model
model.fit(X_train, y_train)

print("Linear Regression model trained successfully!")

# Use the trained model to predict ratings for the test data
y_pred = model.predict(X_test)

# Display the first 10 predicted ratings
print("First 10 Predicted Ratings:")
print(y_pred[:10])

# Calculate Mean Absolute Error
mae = mean_absolute_error(y_test, y_pred)

# Calculate Root Mean Squared Error
rmse = np.sqrt(mean_squared_error(y_test, y_pred))

# Calculate R-squared score
r2 = r2_score(y_test, y_pred)

# Display the results
print("Model Performance")
print("-------------------------")
print("Mean Absolute Error:", round(mae, 3))
print("Root Mean Squared Error:", round(rmse, 3))
print("R2 Score:", round(r2, 3))

# Create a scatter plot comparing actual and predicted ratings
plt.figure(figsize=(8, 6))

plt.scatter(y_test, y_pred)

# Create a reference line
plt.plot(
    [y_test.min(), y_test.max()],
    [y_test.min(), y_test.max()],
    linestyle="--"
)

# Add title and labels
plt.title("Actual vs Predicted Movie Ratings")
plt.xlabel("Actual Rating")
plt.ylabel("Predicted Rating")

# Display the graph
plt.show()

# Create information for a sample movie
# Year = 2024
# Duration = 120 minutes
# Votes = 5000

sample_movie = pd.DataFrame({
    "Year": [2024],
    "Duration": [120],
    "Votes": [5000]
})

# Predict the rating
predicted_rating = model.predict(sample_movie)

# Display the predicted rating
print(
    "Predicted Movie Rating:",
    round(predicted_rating[0], 2)
)

